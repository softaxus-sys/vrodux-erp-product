// ─── Types ────────────────────────────────────────────────────────────────────
export type PropertyType = "residential" | "commercial" | "mixed_use" | "industrial" | "retail";
export type PropertyStatus = "active" | "inactive" | "under_development";
export type UnitType = "apartment" | "villa" | "office" | "retail_shop" | "warehouse" | "studio";
export type UnitStatus = "vacant" | "rented" | "reserved" | "maintenance" | "for_sale" | "sold";
export type TenantStatus = "active" | "inactive" | "blacklisted";
export type ContractStatus = "draft" | "active" | "expiring_soon" | "expired" | "terminated";
export type BrokerStatus = "active" | "inactive";
export type PaymentHistory = "excellent" | "good" | "fair" | "poor";

// ─── Interfaces ───────────────────────────────────────────────────────────────
export interface Property {
  id: string;
  propertyCode: string;
  name: string;
  type: PropertyType;
  status: PropertyStatus;
  location: { address: string; city: string; emirate: string };
  developer: string;
  totalUnits: number;
  vacantUnits: number;
  occupancyRate: number;
  totalValue: number;
  annualRent: number;
  managedBy: string;
  yearBuilt: number;
  facilities: string[];
}

export interface Unit {
  id: string;
  unitNumber: string;
  propertyId: string;
  propertyName: string;
  type: UnitType;
  status: UnitStatus;
  floor: number;
  area: number;
  bedrooms: number | null;
  bathrooms: number;
  rentPricePA: number;
  salePriceIfForSale: number | null;
  tenantId: string | null;
  tenantName: string | null;
  contractId: string | null;
  contractExpiry: string | null;
  lastMaintenanceDate: string | null;
}

export interface Tenant {
  id: string;
  tenantCode: string;
  name: string;
  type: "individual" | "corporate";
  status: TenantStatus;
  contactPerson: string;
  email: string;
  phone: string;
  nationality: string;
  emiratesId: string | null;
  trn: string | null;
  totalUnits: number;
  monthlyRent: number;
  activeContractId: string | null;
  outstandingBalance: number;
  paymentHistory: PaymentHistory;
  joinDate: string;
  notes: string;
}

export interface Broker {
  id: string;
  brokerCode: string;
  name: string;
  agencyName: string;
  rera: string;
  email: string;
  phone: string;
  status: BrokerStatus;
  specializations: PropertyType[];
  rating: number;
  activeListings: number;
  closedDeals: number;
  totalCommission: number;
  avgDealValue: number;
  joinDate: string;
}

export interface Contract {
  id: string;
  contractNumber: string;
  type: "lease" | "sale";
  status: ContractStatus;
  propertyId: string;
  propertyName: string;
  unitId: string;
  unitNumber: string;
  tenantId: string;
  tenantName: string;
  brokerId: string | null;
  brokerName: string | null;
  startDate: string;
  endDate: string;
  rentAmount: number | null;
  saleAmount: number | null;
  depositAmount: number;
  paymentFrequency: "monthly" | "quarterly" | "annual";
  nextPaymentDate: string | null;
  lastPaymentDate: string | null;
  contractDoc: string;
  notes: string;
}

